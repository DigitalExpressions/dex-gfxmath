    template <typename V>
    void expectSwizzle(TestContext& context, const V& value, const std::array<int, V::size()>& indices, std::string_view message)
    {
        expectVector(
            context, value,
            [&](int d, int i)
            {
                return indices[d] * 100 + i + 1;
            },
            0, message);
    }

